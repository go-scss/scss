// Command gen emits a large, self-contained synthetic SCSS stylesheet that
// exercises the heavy paths of the compiler: deep nesting, many mixins and
// @include calls, @extend chains, placeholder selectors, color functions, maps
// and @each loops, math, and media queries. It is deterministic (no imports,
// no randomness) so the emitted bench/corpus/generated.scss is reproducible and
// safe to commit as a stable benchmark fixture.
//
//	go run bench/gen.go > bench/corpus/generated.scss
package main

import (
	"bufio"
	"fmt"
	"os"
)

func main() {
	w := bufio.NewWriter(os.Stdout)
	defer w.Flush()

	fmt.Fprintln(w, "// AUTO-GENERATED by bench/gen.go — do not edit by hand.")
	fmt.Fprintln(w, "// A synthetic but representative heavy stylesheet for benchmarking.")
	fmt.Fprintln(w)

	// A palette map + helpers exercised throughout.
	fmt.Fprintln(w, "$palette: (")
	names := []string{"primary", "secondary", "success", "info", "warning", "danger", "light", "dark"}
	base := []string{"#0d6efd", "#6c757d", "#198754", "#0dcaf0", "#ffc107", "#dc3545", "#f8f9fa", "#212529"}
	for i, n := range names {
		fmt.Fprintf(w, "  %s: %s,\n", n, base[i])
	}
	fmt.Fprintln(w, ");")
	fmt.Fprintln(w)

	// Mixins covering args, defaults, content blocks, math, and color math.
	fmt.Fprintln(w, `@mixin box($pad: 1rem, $radius: .25rem, $col: #333) {`)
	fmt.Fprintln(w, `  padding: $pad;`)
	fmt.Fprintln(w, `  border-radius: $radius;`)
	fmt.Fprintln(w, `  color: $col;`)
	fmt.Fprintln(w, `  border: 1px solid darken($col, 10%);`)
	fmt.Fprintln(w, `  background: mix($col, #fff, 8%);`)
	fmt.Fprintln(w, `}`)
	fmt.Fprintln(w)
	fmt.Fprintln(w, `@mixin respond($min) {`)
	fmt.Fprintln(w, `  @media (min-width: $min) { @content; }`)
	fmt.Fprintln(w, `}`)
	fmt.Fprintln(w)

	// Placeholder selectors for @extend chains.
	for i := 0; i < 12; i++ {
		fmt.Fprintf(w, "%%base-%d { margin: %drem; letter-spacing: %dpx; }\n", i, i%4, i%3)
	}
	fmt.Fprintln(w)

	// A large block of component rules: deep nesting, includes, extends,
	// color functions, and per-breakpoint media queries via @each.
	bp := []string{"576px", "768px", "992px", "1200px"}
	for c := 0; c < 240; c++ {
		fmt.Fprintf(w, ".comp-%d {\n", c)
		fmt.Fprintf(w, "  @include box($pad: %d * .25rem, $col: map-get($palette, %s));\n", (c%6)+1, names[c%len(names)])
		fmt.Fprintf(w, "  @extend %%base-%d;\n", c%12)
		fmt.Fprintln(w, "  display: flex;")
		fmt.Fprintf(w, "  color: lighten(map-get($palette, %s), %d%%);\n", names[(c+1)%len(names)], c%20)
		fmt.Fprintf(w, "  background-color: rgba(map-get($palette, %s), .%d);\n", names[c%len(names)], (c%9)+1)
		// Nested children (depth 3).
		fmt.Fprintln(w, "  .inner {")
		fmt.Fprintln(w, "    font-weight: bold;")
		fmt.Fprintf(w, "    border-color: adjust-hue(map-get($palette, %s), %ddeg);\n", names[c%len(names)], (c*7)%360)
		fmt.Fprintln(w, "    &:hover { text-decoration: underline; }")
		fmt.Fprintln(w, "    .leaf {")
		fmt.Fprintf(w, "      width: percentage(%d / 12);\n", (c%12)+1)
		fmt.Fprintf(w, "      opacity: %d / 10;\n", (c%9)+1)
		fmt.Fprintln(w, "    }")
		fmt.Fprintln(w, "  }")
		// @each producing modifier classes.
		fmt.Fprintln(w, "  @each $name, $val in $palette {")
		fmt.Fprintln(w, "    &--#{$name} { border-left: 3px solid $val; }")
		fmt.Fprintln(w, "  }")
		// Media queries via mixin @content.
		fmt.Fprintf(w, "  @include respond(%s) { padding: %d * .5rem; }\n", bp[c%len(bp)], (c%4)+1)
		fmt.Fprintln(w, "}")
	}

	// A @for loop generating a utility grid (many small rules).
	fmt.Fprintln(w)
	fmt.Fprintln(w, "@for $i from 1 through 60 {")
	fmt.Fprintln(w, "  .u-w-#{$i} { width: percentage($i / 60); }")
	fmt.Fprintln(w, "  .u-p-#{$i} { padding: $i * 1px; }")
	fmt.Fprintln(w, "}")
}
